-- ค่าตรวจรถสมุทรปราการ (ต้นทุน No Bill) รถยนต์ - ผู้ใช้ให้ราคา 2026-11-17: รย.1 500 / รย.2 1,000 / รย.3 500 ทุกยี่ห้อ
-- (รย.12 200 และ รย.17 300 ใส่ไว้แล้วใน 20261008210000 / 20261008230000)
-- ใช้เป็นราคาตั้งต้นตอนบันทึกส่งตรวจเท่านั้น รถที่บันทึกส่งตรวจไปแล้วเก็บราคาไว้เอง (inspectionSentCost) ไม่เปลี่ยน
INSERT INTO "FeeInspectionProvince" ("id", "province", "vehicleType", "amount")
SELECT gen_random_uuid()::text, 'สมุทรปราการ', x.t, x.a
FROM (VALUES
  ('รย.1-เก๋ง 2 ตอน', 500),
  ('รย.1-นั่ง 2 ตอน', 500),
  ('รย.1-นั่ง 3 ตอน', 500),
  ('รย.2-นั่ง 2 แถว', 1000),
  ('รย.2-นั่ง 4 ตอน', 1000),
  ('รย.3-กระบะบรรทุก', 500),
  ('รย.3-กระบะบรรทุกมีหลังคา', 500),
  ('รย.3-กระบะบรรทุกมีหลังคาแหนบ', 500),
  ('รย.3-ตู้บรรทุก', 500)
) AS x(t, a)
ON CONFLICT ("province", "vehicleType") DO UPDATE SET "amount" = EXCLUDED."amount";
